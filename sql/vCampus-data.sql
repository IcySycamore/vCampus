-- 谁执行它：
--   · 服务端测试：TestSchemaSetup 在重建出 <开发库>_test 之后随即执行（测试库每次运行都是新的，
--     所以测试要用的行必须由脚本喂进去，而不是由 Java 代码在测试里「补一行」）；
--   · CI：建库脚本之后执行一次，让开发库也有完整引用数据；
--   · 本地演示：想看到课表就执行它。
--
-- 幂等：可重复执行（先删同 uuid 的行再插），uuid 全部写死，重复执行不会堆出第二套。
-- =====================================================================

